// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol
// is pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown with the market's own values, never mixed
// into the ranked board. Say a protocol records no token, never that it has none: DefiLlama's record
// is not proof.
//
// Implied value follows only from the snapshot's own figures, through four factors:
//
//   multiple  = clamp(0.30 x (100,000,000 / tvl_usd)^0.12, 0.08, 0.45)
//               A token's plausible value is a multiple of TVL, and the multiple falls as a protocol
//               grows: a $50M protocol can plausibly trade at a third of its TVL, a $2.7B one cannot
//               keep that multiple. The power law is smooth, so no TVL band is a cliff.
//   growth    = clamp(change_7d, -50, 150) per cent
//   growthMul = 1 + (growth / 100) x 0.6
//               Seven-day TVL growth, clamped hard: one week of +4,448% (the snapshot's own maximum)
//               must not crown a protocol by itself, and a -73% week must not erase one.
//   maturity  = 0.45 + 0.55 x (1 - exp(-age_days / 365))
//               Age is the time since DefiLlama first listed the protocol, the best record of how
//               long it has run with no token. It saturates: a year with no token is nearly as seasoned
//               as three, and a protocol listed last week scores 0.45, not a full year of credit.
//               Age unknown: 365 days.
//   breadth   = 1 + 0.03 x min(chains - 1, 9)
//               A protocol counted on more chains has more places a launch can land; capped at 1.27.
//
//   implied   = max(1, round(tvl_usd x multiple x growthMul x maturity x breadth))
//
// The constants are the model's, stated in the dashboard and changeable in its sandbox. No protocol
// name is ever special-cased: the same function scores every row, and the dashboard recomputes each
// row from the same figures so the page and board.json agree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

